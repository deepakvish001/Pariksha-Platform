// Helper to generate problems for a problem set
function generateProblems(
  setId: number,
  count: number,
  baseDifficulty: "Easy" | "Medium" | "Hard",
  titles: string[],
  platform?: string
): CPProblem[] {
  const difficulties: ("Easy" | "Medium" | "Hard")[] = [];
  
  // Distribute difficulties based on base difficulty
  for (let i = 0; i < count; i++) {
    if (baseDifficulty === "Easy") {
      difficulties.push(i < count * 0.7 ? "Easy" : i < count * 0.9 ? "Medium" : "Hard");
    } else if (baseDifficulty === "Medium") {
      difficulties.push(i < count * 0.3 ? "Easy" : i < count * 0.8 ? "Medium" : "Hard");
    } else {
      difficulties.push(i < count * 0.1 ? "Easy" : i < count * 0.4 ? "Medium" : "Hard");
    }
  }

  return Array.from({ length: count }, (_, i) => ({
    id: setId * 1000 + i + 1,
    title: titles[i] || `Problem ${i + 1}`,
    difficulty: difficulties[i],
    platform,
  }));
}

// Generate contest problems
function generateContestProblems(setId: number, count: number, platform: string): CPProblem[] {
  const labels = ["A", "B", "C", "D", "E", "F", "G", "H"];
  return Array.from({ length: count }, (_, i) => ({
    id: setId * 1000 + i + 1,
    title: `Problem ${labels[i] || String.fromCharCode(65 + i)}`,
    difficulty: i < 2 ? "Easy" : i < 4 ? "Medium" : "Hard",
    platform,
  }));
}

